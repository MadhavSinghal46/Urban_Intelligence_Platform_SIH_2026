export const getValidEvents = (events = mockEvents) =>
  events.filter((event) => Number.isFinite(event.latitude) && Number.isFinite(event.longitude))

export const formatConfidence = (value) => `${Math.round((value || 0) * 100)}%`

export const buildDeviceStats = (events = mockEvents) => {
  const map = new Map()

  events.forEach((event) => {
    const key = event.device_id
    if (!map.has(key)) {
      map.set(key, {
        device_id: key,
        busName: mockDeviceProfiles[key]?.busName || key,
        potholes: 0,
        confidenceTotal: 0,
        status: mockDeviceProfiles[key]?.status || 'Operational',
      })
    }

    const stats = map.get(key)
    stats.potholes += 1
    stats.confidenceTotal += Number(event.confidence || 0)
  })

  return [...map.values()].map((item) => ({
    ...item,
    averageConfidence: item.potholes ? item.confidenceTotal / item.potholes : 0,
  })).sort((a, b) => b.potholes - a.potholes)
}

export const getDashboardSummary = (events = mockEvents) => {
  const validEvents = getValidEvents(events)
  const totalEvents = validEvents.length
  const averageConfidence =
    totalEvents > 0
      ? validEvents.reduce((sum, event) => sum + Number(event.confidence || 0), 0) / totalEvents
      : 0

  return {
    totalPotholes: totalEvents,
    devicesCount: new Set(validEvents.map((event) => event.device_id)).size,
    averageConfidence,
    serverStatus: 'Operational',
  }
}
